// Writes public/robots.txt and public/sitemap.xml before the storefront build.
//
// Why at build time: the catalog (public/catalog.json) changes with every
// scraper run, and a SPA answers index.html for any path, so without real files
// Lighthouse flagged "robots.txt is not valid" and search engines had no list
// of product pages to crawl. Pages that belong to a person (checkout, orders,
// the panel, the seller panel) are kept out of the index.
//
// Site URL: VITE_SITE_URL, else Vercel's production URL, else the live store.
// Run: node scripts/gen-seo.mjs   (scripts/vercel-build.sh does it)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(ROOT, "public");

const explicit = (process.env.VITE_SITE_URL || "").trim();
const vercelProd = (process.env.VERCEL_PROJECT_PRODUCTION_URL || "").trim();
const SITE = (explicit || (vercelProd ? `https://${vercelProd}` : "https://www.rubilens.com")).replace(/\/+$/, "");

const slugOf = (sku) => String(sku).toLowerCase().replace(/[^a-z0-9]+/g, "");
const today = new Date().toISOString().slice(0, 10);

let products = [];
try {
  products = JSON.parse(readFileSync(join(PUBLIC, "catalog.json"), "utf8"));
} catch {
  // No catalog (fresh clone): the sitemap still lists the static pages.
}
const brands = [...new Set(products.map((p) => p.brand_slug).filter(Boolean))].sort();

const urls = [
  { loc: "/", priority: "1.0", changefreq: "weekly" },
  { loc: "/catalogo", priority: "0.9", changefreq: "daily" },
  { loc: "/estuches", priority: "0.6", changefreq: "weekly" },
  ...brands.map((b) => ({ loc: `/marca/${b}`, priority: "0.8", changefreq: "weekly" })),
  ...products.map((p) => ({ loc: `/producto/${slugOf(p.sku)}`, priority: "0.7", changefreq: "weekly" })),
];

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const sitemap =
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  urls.map((u) => `  <url><loc>${esc(SITE + u.loc)}</loc><lastmod>${today}</lastmod><changefreq>${u.changefreq}</changefreq><priority>${u.priority}</priority></url>`).join("\n") +
  `\n</urlset>\n`;

const robots = [
  "# Generated by scripts/gen-seo.mjs at build time — edit the script, not this file.",
  "User-agent: *",
  "Allow: /",
  // Personal or operational pages: never indexed.
  "Disallow: /admin",
  "Disallow: /admin_stores",
  "Disallow: /checkout",
  "Disallow: /cuenta",
  "Disallow: /my-orders",
  "Disallow: /vendedor",
  "Disallow: /dev/",
  "Disallow: /medusa/",
  "Disallow: /medusa-staging/",
  "",
  `Sitemap: ${SITE}/sitemap.xml`,
  "",
].join("\n");

writeFileSync(join(PUBLIC, "sitemap.xml"), sitemap);
writeFileSync(join(PUBLIC, "robots.txt"), robots);
console.log(`gen-seo: ${urls.length} URLs for ${SITE} (${brands.length} brands, ${products.length} products)`);
