/** Fast lookup by normalised key. */
export const CAPRI_BY_KEY: ReadonlyMap<string, CapriPrice> = new Map(
  CAPRI_PRICE_LIST.map((p) => [p.key, p])
);

/**
 * The catalogue's SKU → the supplier's key. Two shapes the plain normalisation
 * does not catch, both found by comparing the list against the real catalogue:
 *   · four frames the catalogue prefixes with "YC" (YC21102 → 21102);
 *   · "DI CAPRIO CASE", which the supplier's PDF truncates to "DI CAPRIO CAS".
 * Anything else falls through unchanged.
 */
export function capriKeyOf(sku: string): string {
  const key = String(sku ?? "").toUpperCase().replace(/[^A-Z0-9]/g, "");
  if (CAPRI_BY_KEY.has(key)) return key;
  if (key.startsWith("YC") && CAPRI_BY_KEY.has(key.slice(2))) return key.slice(2);
  if (key === "DICAPRIOCASE" && CAPRI_BY_KEY.has("DICAPRIOCAS")) return "DICAPRIOCAS";
  return key;
}

/** The supplier's cost for a catalogue SKU, or null when the list has no row. */
export function capriCostCents(sku: string): number | null {
  return CAPRI_BY_KEY.get(capriKeyOf(sku))?.cost_cents ?? null;
}
