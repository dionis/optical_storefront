/** Fast lookup by normalised key (first row wins on a duplicate). */
export const CAPRI_PREV_BY_KEY: ReadonlyMap<string, CapriPrevPrice> = (() => {
  const out = new Map<string, CapriPrevPrice>();
  for (const p of CAPRI_PREV_PRICE_LIST) if (!out.has(p.key)) out.set(p.key, p);
  return out;
})();

/** Normalises like the 2026 list: upper case, A-Z0-9 only. */
const plain = (s: string): string => String(s ?? "").toUpperCase().replace(/[^A-Z0-9]/g, "");

/**
 * The previous list's cost for a key (or a model spelled any way the catalogue
 * spells it), in cents; null when the old book has no row or only estimated it.
 */
export function capriPrevCostCents(key: string): number | null {
  return CAPRI_PREV_BY_KEY.get(plain(key))?.wholesale_cents ?? null;
}
