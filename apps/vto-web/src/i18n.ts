const DICTS: Record<Lang, Dict> = { es: ES, en: EN };
const STORAGE_KEY = 'vto-lang';

function detectInitialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'es' || saved === 'en') return saved;
  } catch {
    /* localStorage unavailable (private mode); fall through to the default */
  }
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'es';
}

let current: Lang = detectInitialLang();
const listeners: Array<() => void> = [];

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (lang !== 'es' && lang !== 'en') return;
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* not persisting is acceptable */
  }
  document.documentElement.lang = lang;
  applyTranslations();
  listeners.forEach((cb) => cb());
}

/** Registers a callback for anything that must be re-rendered on a language switch. */
export function onLangChange(cb: () => void): void {
  listeners.push(cb);
}

/** Looks up a key and interpolates {placeholders}. Unknown keys return the key itself. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[current][key] ?? DICTS.es[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] !== undefined ? String(vars[name]) : match
  );
}

/**
 * Applies translations to every element carrying a data-i18n attribute.
 * `data-i18n-html` marks strings that legitimately contain inline markup.
 */
export function applyTranslations(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n!;
    if (el.hasAttribute('data-i18n-html')) el.innerHTML = t(key);
    else el.textContent = t(key);
  });

  // Controls whose only label is an icon still need a name for a screen reader
  root.querySelectorAll<HTMLElement>('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel!));
  });

  // A textarea's prompt to the user lives in its placeholder, so it needs translating
  // as much as any label does.
  root.querySelectorAll<HTMLElement>('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder!));
  });
}
